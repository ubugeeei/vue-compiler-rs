test("tool benchmark fairness notes report the measured corpus size", () => {
  const notes = buildFairnessNotes(3000);

  assert.ok(
    notes.includes(
      "The 3,000-SFC rows are the many-file workload; the large-SFC rows isolate one large component.",
    ),
  );
  assert.equal(
    notes.some((note) => note.includes("15,000-SFC")),
    false,
  );
});

test("the Nuxt fairness note states the Vue-compilation share and where the module's own cost is measured", () => {
  // The Nuxt row is an end-to-end `nuxt build`, and SFC compilation is ~2% of
  // it, so it cannot be read as a compiler comparison. The note must say so,
  // and must point at the benchmark that does isolate the Vize Nuxt module.
  const nuxtNotes = buildFairnessNotes(500).filter((note) => note.startsWith("Nuxt SPA build"));

  assert.deepEqual(nuxtNotes, [
    "Nuxt SPA build timings exclude synthetic app generation and compare `nuxt build` with Nuxt's default compiler against the same app with `@vizejs/nuxt` installed. Vue SFC compilation is roughly 2% of that build (measured on the 500-file corpus in #3426), so this row cannot be moved by making the Vue compiler faster — it is dominated by Nitro, Rollup and Nuxt's own module graph work. `tools/benchmarks/scripts/nuxt-bridge-transform.mjs` isolates the part of this surface Vize does own, the Nuxt module's per-module bridge transform.",
  ]);

  const publishedDoc = fs.readFileSync(
    path.join(root, "docs/content/architecture/performance-blacksmith.md"),
    "utf-8",
  );
  assert.equal(publishedDoc.includes(`- ${nuxtNotes[0]}`), true);
});

test("legacy typecheck benchmark does not publish cross-engine ratios", () => {
  const script = fs.readFileSync(path.join(root, "tools/benchmarks/scripts/check.ts"), "utf-8");

  assert.doesNotMatch(script, /\$\{[^}]+}x faster/);
  assert.doesNotMatch(script, /user-facing speedup/);
  assert.doesNotMatch(script, /vue-tsc ST vs Vize/);
  assert.doesNotMatch(script, /vue-tsc MT vs Vize/);
  assert.match(script, /This legacy local harness reports timings only/);
  assert.match(script, /same-native-engine rows such as verter-tsc and\s+\*\s+Golar/);
});

test("native batch sequence variants require parallel capacity", () => {
  const options = {
    native: {},
    pattern: "fixtures/*.vue",
    expectedFiles: 1,
  };

  assert.deepEqual(createNativeBatchSequenceVariants({ ...options, maxThreads: 1 }), []);
  assert.deepEqual(
    createNativeBatchSequenceVariants({ ...options, maxThreads: 4 }).map(({ id }) => id),
    ["vize-native-sequence-1-max", "vize-native-sequence-max-1"],
  );
});
